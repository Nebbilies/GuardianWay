import { Router } from "express";
import { list, get, create, revise, update, transition } from "./schedule.controller";
export const scheduleRouter = Router();
scheduleRouter.get("/", list);
scheduleRouter.get("/:id", get);
scheduleRouter.post("/", create);
scheduleRouter.put("/:id", update);
scheduleRouter.post("/:id/versions", revise);
scheduleRouter.post("/:id/activate", transition("activate"));
scheduleRouter.post("/:id/deactivate", transition("deactivate"));
